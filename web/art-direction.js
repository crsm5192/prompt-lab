// 构图偏好只引导未指定的视觉选择；具体场景、动作、机位和画幅始终优先。
export const COMPOSITION_MODES = Object.freeze({
  auto: {
    label: '自动艺术构图',
    instruction: '按题材选择有意图的构图：人物互动重视视线与接触路径，动态重视动作线和运动空间，静物重视形体与留白，建筑重视透视和几何秩序。说明焦点所在区域、主体与背景的明暗大形、视线如何在画面中流动；允许有依据的对称或偏置，不固定套居中、三分法或倾斜机位。',
  },
  preserve: {
    label: '保留已有构图',
    instruction: '保留原有主体位置、景别、机位、画幅、遮挡和视线走向。用原有布局中的明暗层次、边缘控制、局部色彩与材质提升完成度，不重排画面。',
  },
  negative_space: {
    label: '偏置与留白',
    instruction: '在硬约束允许的范围内偏置主体，给视线或动作方向留下呼吸空间；用主体与空白区域的尺寸和明暗对比取得平衡。留白有明确位置与形状，不等于清空用户要求的环境。',
  },
  diagonal: {
    label: '对角线与动势',
    instruction: '让动作线、道具或场景中的已有线条形成连贯对角动势，并以稳定的次要形体平衡重心；给运动方向留空间。保持人体关节和透视自然，不靠极端广角、歪地平线或夸张肢体制造动感。',
  },
  framing: {
    label: '框景与空间层次',
    instruction: '用场景中已有的门窗、枝叶或建筑边缘形成框景，组织近、中、远景和前后尺度。保留真实遮挡关系，框景不压住关键动作与接触点；没有合适前景时通过空间和明度层次构图，不凭空加道具。',
  },
  geometric: {
    label: '几何秩序与节奏',
    instruction: '用已有形体的对齐、重复、间距和疏密组织画面，确定对称或非对称平衡，并让核心主体成为节奏中的停顿或重音。保持真实数量，不为重复图案复制人物或道具，不额外生成网格、边框或文字。',
  },
})

export function qualityDirection(args = {}, mode = 'gen') {
  const key = Object.hasOwn(COMPOSITION_MODES, args.composition) ? args.composition : 'auto'
  const selected = COMPOSITION_MODES[key]
  const lines = [
    '【画面精度与艺术设计】明确的身份、数量、服装、动作、左右手、物体、遮挡、镜头、画幅、光源和原有媒介优先于任何增强偏好；触发词原样保留。',
    '人物或动物存在时，只为可见且影响动作的部位写清姿态、承重和接触：哪只手持什么、手与物体怎样接触、肢体归属谁、脚或身体由哪里支撑；同一瞬间的动作要物理协调。手脚不可见时不猜测，不用藏手、裁脚、限制动作数量来回避困难；保留用户明确要求的非现实结构。无人画面不加人体词。',
  ]
  if (mode === 'reverse') {
    lines.push('本次为忠实反推：准确还原可见构图、色块、光照、材质、姿态和遮挡；不设计新机位、不重新布光、不补隐藏手脚，也不根据构图偏好重排原图。')
  } else if (mode === 'iterate') {
    lines.push('本次为局部迭代：仅在反馈要求的范围内改善。未被要求改动的构图、动作、接触关系、材质和媒介保持；只有反馈要求重新构图时才重新设计，不能因默认增强而重排上一版。')
    if (key !== 'auto') lines.push(`反馈允许改变构图时采用「${selected.label}」：${selected.instruction}`)
  } else {
    lines.push(`构图偏好「${selected.label}」：${selected.instruction}`)
    lines.push('质感与美术：在当前媒介内安排有来源的主光、明暗大形、主辅色及局部强调色，写出它们所在区域和视觉作用；区分皮肤、布料、金属等受光表现。绘画用焦点附近清晰边缘、次要区域虚实变化和具体笔触组织，摄影保持真实表面与合理镜头，不默认把插画改成照片。')
  }
  lines.push('景别必须容纳用户要求看见的部位：全身或双脚完整入镜时，不同时写半身/特写；只拍头肩时不追加画外腿脚。画面只保留彼此兼容的焦距、透视与景深描述。')
  lines.push(args.familyKind === 'tag'
    ? '本族只输出短标签：用模型熟悉的动作主锚点与必要的左右接触关系，保留服装、景别和核心构图。一个含义选择最明确的写法，不叠加同义镜头、站姿、承重、可见手脚和道具单数标签；删泛词与重复材质词，不把自检目录全部抄成标签，不混入散文，不自创长句标签。'
    : '将最关键的接触关系、构图和光色选择写进正向正文，用当前族要求的标签/散文/Layout 表达；不把全部自检项变成提示词清单。')
  if (args.familyKind === 'tag+NL') {
    lines.push('【Anima 精简与动作锚点】第一行用短标签前置主体身份、人数、服饰和关键动作，保留触发词与媒介；通常 8–16 个有信息量的锚点，明确设定较多时允许增加。标签里的静态事实不逐项复述；真换行后 2–3 句正文依次补充动作接触与连续姿态、构图和媒介内的光色。普通场景优先约 180–240 token，复杂关系可至 300；不为凑长度加天气、道具或背景清单，精简不能丢用户指定信息。')
    lines.push('【Anima 动态人物】把同一人的头颈与躯干朝向、手臂归属、腿的前伸/后弯及承重状态合并为一帧可成立的动作。全身动态需要容纳完整轮廓；只按用户要求及可见信息决定面部朝向，不擅自加后仰、扭颈、低机位或极端透视来制造动势。跳跃明确脚与地面的间隙，站姿保持接地；手持物只写必要接触，不逐根安排手指，不靠裁切或藏手规避。')
  } else if (args.familyKind === 'NL+layout') {
    if (mode === 'iterate') lines.push('本次 MOSS 局部迭代保留上一版的 caption/tag/Layout 形态和未指定修改的文字、位置与关系；只有反馈要求切换形态或重新布局时才改变。')
    lines.push('【MOSS 主体与关系优先】普通场景默认完整英文画面描述，开头先绑定主体、数量与关键动作，随即写左右手/物体接触和视线目标，再用少量句子写主体位置、空间关系、构图与媒介内的光色材质。通常约 180–280 token，指定信息较多可增加；同一事实只写一次，不为高级感逐个展开头、手、脚、镜头参数和材质自检表。')
    lines.push('【MOSS 形态与媒介】只有用户要复用标签时用 tag 串；文字精确落位、多元素位置约束或分格排版才用 Layout，普通多人或细节丰富不等于必须 Layout。全局风格放 summary.caption，各人物/道具关系绑定到对应 item，不把手指当独立 bbox；坐标不决定握持关系。水彩以纸纹、洗色和边缘虚实表达，摄影以真实表面响应表达；不擅自加塑料皮肤、湿亮布料或 3D 渲染。用户提供的触发词保留，若与媒介明显冲突在 notes 说明，不编造未知 LoRA 设置。')
  } else if (args.familyKind === 'NL') {
    lines.push('自然语言先交代主体与关键动作接触，再交代构图，最后交代光色和材质；同一个事实只写一次。把人物位置、视线或动作线合并成简洁的空间描述，不围绕头、手、脚反复绕行，不把手指握法、镜头参数和全部材质自检项展开成清单。')
  }
  lines.push('负面中的媒介词必须有明确依据：anime、cartoon、illustration、painting、watercolor、lineart 等合法画风不能当作人体异常来压制；只有用户明确排除该画风时才放入负面。水彩、绘画与动漫线条可以兼容，不自动把动漫列为水彩的缺陷。')
  lines.push('输出格式要求只控制结构，不属于画面内容：caption、Layout、prompt 等写作词不要混入正向正文，除非它们本来就是用户要求画出的文字。')
  lines.push('提交前自检并消除互斥景别、左右手错配、道具复制、人物特征串联、错误承重、光影方向冲突和媒介漂移。正向只写正确可见状态，不堆叠「高级感/艺术感/电影感/完美人体」评价词；负面只压制与本场景相关的异常，不能误杀用户要求的内容，禁用负面的路线保持空。notes 用至多三条简短中文说明实际构图、动作接触或材质选择，不承诺消除出图畸形。')
  return lines.join('\n')
}
